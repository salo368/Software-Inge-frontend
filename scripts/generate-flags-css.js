/**
 * Generates projects/shared/src/styles/flags.css: one rule per country listed in
 * projects/shared/src/core/dial-codes.ts, pointing at the SVG that the
 * `flag-icons` package ships.
 *
 * Why not import flag-icons' own CSS: it declares every flag twice (4x3 and 1x1),
 * so the build would copy ~540 SVGs. Only the 4x3 ones of our 196 countries are
 * needed. Run it again whenever DIAL_CODES gains or loses a country:
 *
 *   node scripts/generate-flags-css.js
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'projects/shared/src/core/dial-codes.ts'), 'utf8');
const table = source.slice(source.indexOf('DIAL_CODES'), source.indexOf('};', source.indexOf('DIAL_CODES')));
const isos = [...table.matchAll(/\b([A-Z]{2}):\s*'\d+'/g)].map((m) => m[1].toLowerCase());

if (isos.length < 150) throw new Error(`Solo encontré ${isos.length} países en dial-codes.ts: ¿cambió el formato?`);

const flagsDir = path.join(root, 'node_modules/flag-icons/flags/4x3');
const missing = isos.filter((iso) => !fs.existsSync(path.join(flagsDir, `${iso}.svg`)));
if (missing.length) throw new Error(`flag-icons no trae la bandera de: ${missing.join(', ')}`);

const rel = '../../../../node_modules/flag-icons/flags/4x3';
const css = [
  '/* GENERATED by scripts/generate-flags-css.js from core/dial-codes.ts. Do not edit by hand.',
  ' * Flags: https://github.com/lipis/flag-icons (MIT). Windows has no flag emoji glyphs, so',
  ' * these are images shipped with the app instead of depending on an external server. */',
  '.fi {',
  '  display: inline-block;',
  '  flex: none;',
  '  width: 1.33333em;',
  '  height: 1em;',
  '  line-height: 1em;',
  '  background-size: contain;',
  '  background-position: 50%;',
  '  background-repeat: no-repeat;',
  '  border-radius: 0.12em;',
  '  box-shadow: 0 0 0 1px rgba(23, 20, 58, 0.14);',
  '}',
  ...isos.map((iso) => `.fi-${iso} { background-image: url('${rel}/${iso}.svg'); }`),
  '',
].join('\n');

fs.writeFileSync(path.join(root, 'projects/shared/src/styles/flags.css'), css);
console.log(`flags.css: ${isos.length} banderas`);
